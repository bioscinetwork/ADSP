def create_scaffold(project_root: Path) -> None:
    """Create the AutoDock Suite Pro project folder scaffold.

    Creates:
        receptors/
            README.txt
            example_receptor/
                rigid/
                    PLACE_RIGID_RECEPTOR_PDBQT_HERE.txt
                flex/
                    PLACE_RIGID_BACKBONE_PDBQT_HERE.txt
                    PLACE_FLEX_SIDECHAIN_PDBQT_HERE.txt
                config.txt         (stub with placeholder values)
        ligands/
            README.txt
    """
    rec_dir = project_root / "receptors"
    lig_dir = project_root / "ligands"
    example_dir = rec_dir / "example_receptor"

    # receptors/README.txt
    rec_dir.mkdir(parents=True, exist_ok=True)
    (rec_dir / "README.txt").write_text(RECEPTOR_README, encoding="utf-8")

    # receptors/example_receptor/rigid/
    rigid_dir = example_dir / "rigid"
    rigid_dir.mkdir(parents=True, exist_ok=True)
    (rigid_dir / "PLACE_RIGID_RECEPTOR_PDBQT_HERE.txt").write_text(
        "Replace this file with your rigid receptor .pdbqt file.\n"
        "Example filename: example_receptor.pdbqt\n",
        encoding="utf-8",
    )

    # receptors/example_receptor/flex/ (optional, shows expected layout)
    flex_dir = example_dir / "flex"
    flex_dir.mkdir(parents=True, exist_ok=True)
    (flex_dir / "PLACE_RIGID_BACKBONE_PDBQT_HERE.txt").write_text(
        "Replace with the RIGID backbone PDBQT (passed to Vina --receptor).\n"
        "Typical name: example_receptor_rigid.pdbqt\n"
        "Prepared with: prepare_flexreceptor4.py -r receptor.pdbqt -s A:315_A:316\n",
        encoding="utf-8",
    )
    (flex_dir / "PLACE_FLEX_SIDECHAIN_PDBQT_HERE.txt").write_text(
        "Replace with the FLEXIBLE sidechain PDBQT (passed to Vina --flex).\n"
        "Typical name: example_receptor_flex.pdbqt\n"
        "Prepared with: prepare_flexreceptor4.py -r receptor.pdbqt -s A:315_A:316\n",
        encoding="utf-8",
    )

    # receptors/example_receptor/config.txt (stub)
    write_vina_config(
        example_dir / "config.txt",
        center_x=0.0, center_y=0.0, center_z=0.0,
        size_x=25.0, size_y=25.0, size_z=25.0,
    )
    # Add a note at the top of the stub config
    stub_config = example_dir / "config.txt"
    existing = stub_config.read_text(encoding="utf-8")
    stub_config.write_text(
        "# EDIT THIS FILE: set the correct grid center and size for your receptor.\n"
        + existing,
        encoding="utf-8",
    )

    # ligands/README.txt
    lig_dir.mkdir(parents=True, exist_ok=True)
    (lig_dir / "README.txt").write_text(LIGAND_README, encoding="utf-8")

    # Output directories & structured results subfolders
    for sub in (
        "results", "results/DLG", "results/DPF", "results/VINA", "results/BSNDVP_RESULTS",
        "DLG", "BSNDVP_RESULTS", "logs", "reports"
    ):
        (project_root / sub).mkdir(parents=True, exist_ok=True)

    # Informational placeholders in results folders
    (project_root / "results/DLG/README.txt").write_text(
        "AutoDock 4 Docking Log Files (.dlg) are placed here automatically after docking.\n",
        encoding="utf-8",
    )
    (project_root / "results/DPF/README.txt").write_text(
        "AutoDock 4 Docking Parameter Files (.dpf) used for docking are placed here.\n",
        encoding="utf-8",
    )
    (project_root / "results/VINA/README.txt").write_text(
        "AutoDock Vina output docking pose PDBQT files are placed here.\n",
        encoding="utf-8",
    )

    # Copy dlg_extract.py into workspace for standalone post-processing
    suite_dlg_extract = Path(__file__).resolve().parent / "dlg_extract.py"
    target_dlg_extract = project_root / "dlg_extract.py"
    if suite_dlg_extract.is_file() and not target_dlg_extract.is_file() and project_root.resolve() != suite_dlg_extract.parent.resolve():
        try:
            shutil.copy2(suite_dlg_extract, target_dlg_extract)
            logger.info(f"Copied dlg_extract.py to workspace: {target_dlg_extract}")
        except Exception as e:
            logger.warning(f"Could not copy dlg_extract.py: {e}")

    # Workspace-local bin directory with bundled tools
    target_bin = project_root / "bin"
    suite_bin = Path(__file__).resolve().parent / "bin"
    has_bin = False
    if suite_bin.is_dir() and project_root.resolve() != suite_bin.parent.resolve():
        try:
            target_bin.mkdir(parents=True, exist_ok=True)
            shutil.copytree(suite_bin, target_bin, dirs_exist_ok=True)
            has_bin = True
            logger.info(f"Copied suite binaries to workspace: {target_bin}")
        except Exception as e:
            logger.warning(f"Could not copy binaries to {target_bin}: {e}")
    elif (project_root / "bin").is_dir():
        has_bin = True

    # Generate full self-contained project_config.toml if not present
    toml_path = project_root / "project_config.toml"
    if not toml_path.is_file():
        try:
            from config import generate_template_config
            generate_template_config(toml_path)
            txt = toml_path.read_text(encoding="utf-8")
            txt = txt.replace('name = "Docking_Project"', f'name = "{project_root.name}"')
            toml_path.write_text(txt, encoding="utf-8")
        except Exception as e:
            logger.warning(f"Could not write template config: {e}")

    print()
    print("=" * 60)
    print("  AUTODOCK SUITE PRO -- SCAFFOLD CREATED")
    print("=" * 60)
    print(f"  {rec_dir / 'README.txt'}")
    print(f"  {example_dir / 'rigid'}  <- place your rigid PDBQT here")
    print(f"  {example_dir / 'flex'}   <- place flex PDBQTs here (optional)")
    print(f"  {example_dir / 'config.txt'}")
    print(f"  {lig_dir / 'README.txt'}")
    if has_bin:
        print(f"  {target_bin}  <- bundled executables (vina, autogrid4, autodock4, obabel)")
    print(f"  {project_root / 'results' / 'DLG'}  <- AutoDock4 DLG files will be saved here")
    print(f"  {project_root / 'results' / 'DPF'}  <- AutoDock4 DPF parameter files")
    print(f"  {toml_path}  <- project configuration")
    print()
    print("  Next steps:")
    print("  1. Copy your receptor PDBQT into receptors/<name>/rigid/")
    print("  2. Copy your ligand PDBQTs into ligands/")
    print("  3. Edit receptors/<name>/config.txt with the correct grid center/size")
