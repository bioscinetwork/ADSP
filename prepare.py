def write_vina_config(
    config_path: Path,
    center_x: float,
    center_y: float,
    center_z: float,
    size_x: float,
    size_y: float,
    size_z: float,
    exhaustiveness: int = 8,
    num_modes: int = 9,
    energy_range: float = 6.0,
) -> None:
    """Write a Vina-format config.txt file.

    Args:
        config_path: Where to write the file.
        center_x/y/z: Grid box center coordinates (Angstroms).
        size_x/y/z: Grid box dimensions (Angstroms).
        exhaustiveness: Search exhaustiveness.
        num_modes: Maximum number of binding poses.
        energy_range: Maximum energy range (kcal/mol).
    """
    content = (
        f"# AutoDock Vina Configuration File\n"
        f"# Generated by AutoDock Suite Pro\n"
        f"#\n"
        f"# Grid Box Center (Angstroms)\n"
        f"center_x = {center_x:.3f}\n"
        f"center_y = {center_y:.3f}\n"
        f"center_z = {center_z:.3f}\n"
        f"\n"
        f"# Grid Box Size (Angstroms)\n"
        f"size_x = {size_x:.3f}\n"
        f"size_y = {size_y:.3f}\n"
        f"size_z = {size_z:.3f}\n"
        f"\n"
        f"# Search parameters\n"
        f"exhaustiveness = {exhaustiveness}\n"
        f"num_modes = {num_modes}\n"
        f"energy_range = {energy_range:.1f}\n"
    )
    config_path.parent.mkdir(parents=True, exist_ok=True)
    config_path.write_text(content, encoding="utf-8")
    logger.info(f"Written: {config_path}")


