def prepare_ad4_files(config) -> None:
    """Generate GPF stubs for all receptors (AutoDock4 mode).

    Unlike Vina, GPF is generated per receptor+ligand pair at runtime.
    This function generates a receptor-level GPF stub to confirm grid
    parameters, which can be reviewed before running the full workflow.
    """
    from job_manager import discover_receptors, discover_ligands, find_receptor_config
    from autodock4_workflow import generate_gpf, extract_grid_from_config

    receptors = discover_receptors(config)
    ligands = discover_ligands(config)

    if not receptors:
        print("  [WARN] No receptors found. Run --scaffold to create the folder structure.")
        return
    if not ligands:
        print("  [WARN] No ligands found in ligands/ directory.")

    print()
    print("=" * 60)
    print("  AUTODOCK SUITE PRO — PREPARE: AUTODOCK4 GPF FILES")
    print("=" * 60)

    for rec_name, rec_dir, mode in receptors:
        from job_manager import _find_rigid_pdbqt
        rigid_pdbqt = _find_rigid_pdbqt(rec_dir, rec_name)
        if not rigid_pdbqt:
            print(f"  [SKIP] {rec_name}: no rigid PDBQT found in rigid/")
            continue

        config_txt = find_receptor_config(rec_dir, rec_name)
        grid_params = extract_grid_from_config(config_txt)

        # Use a placeholder ligand PDBQT to determine atom types
        # (GPF will be regenerated properly at docking time)
        if ligands:
            lig_name, lig_path = ligands[0]
        else:
            print(f"  [SKIP] {rec_name}: no ligands found — GPF requires ligand atom types.")
            continue

        # Generate GPF in the receptor folder for review
        gpf_path = rec_dir / f"{rec_name}.gpf"
        generate_gpf(
            rigid_pdbqt, lig_path, gpf_path,
            config,
            grid_params["center"], grid_params["size"],
        )
        print(f"  [OK] {rec_name}: GPF written → {gpf_path}")
        print(f"       Grid center: {grid_params['center']}")
        print(f"       Grid size  : {grid_params['size']}")

    print()
    print("  Review the GPF files above, then run:")
    print("  python main.py --engine AUTODOCK4")
    print("=" * 60)


