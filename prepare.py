def assign_kollman_charges(pdbqt_path: Path | str) -> bool:
    """Assign ADSP's Kollman-style fallback charges; not canonical ADT/MGLTools."""
    path = Path(pdbqt_path)
    if not path.is_file():
        return False

    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    fixed_lines = []
    for line in lines:
        if line.startswith(("ATOM", "HETATM")):
            atom_name = line[12:16].strip()
            res_name = line[17:20].strip().upper()
            element = line[76:78].strip() if len(line) >= 78 else atom_name[0]
            ad_type = line[77:79].strip() if len(line) >= 79 else element.upper()
            if not ad_type:
                ad_type = element.upper()

            # Look up Kollman charge by residue, then backbone
            chg = None
            if res_name in KOLLMAN_RESIDUE_CHARGES:
                chg = KOLLMAN_RESIDUE_CHARGES[res_name].get(atom_name)
            if not chg:
                chg = KOLLMAN_RESIDUE_CHARGES["BACKBONE"].get(atom_name)
            if not chg:
                # Default generic united-atom polar/nonpolar charges
                if element.upper() == "C":
                    chg = "0.000"
                elif element.upper() in ("O", "OA"):
                    chg = "-0.550"
                elif element.upper() in ("N", "NA"):
                    chg = "-0.350"
                elif element.upper() in ("H", "HD"):
                    chg = "+0.275"
                else:
                    chg = "0.000"

            fixed_lines.append(f"{line[:54]:<54}  1.00 20.00    {float(chg):+6.3f} {ad_type:<2s}")
        else:
            fixed_lines.append(line)

    path.write_text("\n".join(fixed_lines) + "\n", encoding="utf-8")
    return True


def ensure_receptor_has_charges(pdbqt_path: Path | str) -> bool:
    """Ensure receptor PDBQT has valid partial atomic charges required by AutoGrid4.

    If all partial charges are 0.000, assigns realistic standard charges.
    """
    path = Path(pdbqt_path)
    if not path.is_file():
        return False

    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    has_charge = False
    atom_count = 0
    for line in lines:
        if line.startswith(("ATOM", "HETATM")) and len(line) >= 68:
            atom_count += 1
            charge_str = line[66:76].strip() if len(line) >= 76 else line[54:68].strip()
            try:
                chg = float(charge_str.split()[0])
                if abs(chg) > 1e-4:
                    has_charge = True
                    break
            except Exception:
                pass

    if has_charge or atom_count == 0:
        return True

    STD_CHARGES = {
        "N": "-0.350", "CA": "+0.100", "C": "+0.250", "O": "-0.270",
        "HN": "+0.160", "H": "+0.160", "HA": "+0.000",
        "OD1": "-0.270", "OD2": "-0.270", "OE1": "-0.270", "OE2": "-0.270",
        "OG": "-0.200", "OG1": "-0.200", "OH": "-0.200", "SG": "-0.100",
        "NZ": "-0.060", "NE": "-0.100", "NH1": "-0.100", "NH2": "-0.100",
        "ND1": "-0.100", "ND2": "-0.100",
    }
    fixed_lines = []
    for line in lines:
        if line.startswith(("ATOM", "HETATM")):
            atom_name = line[12:16].strip()
            element = line[76:78].strip() if len(line) >= 78 else atom_name[0]
            chg = STD_CHARGES.get(atom_name)
            if not chg:
                chg = "+0.050" if element.upper() == "C" else ("-0.200" if element.upper() in ("O", "N", "S") else "+0.100")
            ad_type = line[77:79].strip() if len(line) >= 79 else element.upper()
            if not ad_type:
                ad_type = element.upper()
            fixed_lines.append(f"{line[:54]:<54}  1.00 20.00    {chg} {ad_type:<2s}")
        else:
            fixed_lines.append(line)

    path.write_text("\n".join(fixed_lines) + "\n", encoding="utf-8")
    logger.info(f"Assigned partial atomic charges to {path} for AutoGrid4 compatibility")
    return True


def prepare_ligand_pdbqt(
    input_file: Path | str,
    output_pdbqt: Path | str,
    generate_3d: bool = True,
) -> Dict[str, Any]:
    """Prepares small molecule (SDF/MOL2/PDB/SMI) into a flexible ligand PDBQT.

    Uses Scripps Meeko with RDKit conformer generation, or OpenBabel fallback.

    Args:
        input_file: Path to input structure or SMILES string.
        output_pdbqt: Destination PDBQT path.
        generate_3d: Generate 3D conformer if 2D or SMILES.

    Returns:
        Dictionary of molecular descriptors and preparation metadata.
    """
    in_path = Path(input_file)
    out_path = Path(output_pdbqt)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    def _metal_diagnostics(path: Path) -> Dict[str, Any]:
        try:
            from ad4_compatibility import METAL_REGISTRY, extract_atom_types
            types = extract_atom_types(path)
            metals = []
            for atom_type in types:
                record = METAL_REGISTRY.get(atom_type)
                if record:
                    metals.append({
                        "element": record.element,
                        "atom_type": atom_type,
                        "standard_ad4": record.standard_ad4_parameterized,
                        "specialized_workflows": [record.specialized_workflow] if record.specialized_workflow else [],
                    })
            return {
                "detected": metals,
                "status": "SUPPORTED WITH LIMITATIONS" if metals else "ORDINARY_ORGANIC_LIGAND",
                "requires_user_review": bool(metals),
                "note": "Metal-containing ligands require explicit review of component connectivity, charges, and torsion handling.",
            }
        except Exception as exc:
            return {"detected": [], "status": "UNKNOWN", "requires_user_review": True, "error": str(exc)}

    # 1. Try Scripps Meeko + RDKit
    try:
        import meeko
        from rdkit import Chem
        from rdkit.Chem import AllChem

        ext = in_path.suffix.lstrip(".").lower()
        rd_mol = None

        if ext in ("sdf", "mol"):
            suppl = Chem.SDMolSupplier(str(in_path), removeHs=False)
            rd_mol = next(suppl, None)
        elif ext == "mol2":
            rd_mol = Chem.MolFromMol2File(str(in_path), removeHs=False)
            if rd_mol is None:
                try:
                    rd_mol = Chem.MolFromMol2File(str(in_path), removeHs=False, sanitize=False)
                    if rd_mol is not None:
                        rd_mol.UpdatePropertyCache(strict=False)
                except Exception:
                    rd_mol = None
        elif ext == "pdb":
            rd_mol = Chem.MolFromPDBFile(str(in_path), removeHs=False)
        elif ext in ("smi", "smiles", "txt"):
            smi_text = in_path.read_text(encoding="utf-8").strip().split()[0]
            rd_mol = Chem.MolFromSmiles(smi_text)

        if rd_mol is not None:
            rd_mol = Chem.AddHs(rd_mol)
            if generate_3d or rd_mol.GetNumConformers() == 0:
                AllChem.EmbedMolecule(rd_mol, randomSeed=42)
                AllChem.MMFFOptimizeMolecule(rd_mol)

            preparator = meeko.MoleculePreparation()
            mol_setups = preparator.prepare(rd_mol)
            if not mol_setups:
                raise RuntimeError("Meeko preparation returned empty setup list")

            writer_res = meeko.PDBQTWriterLegacy.write_string(mol_setups[0])
            if isinstance(writer_res, tuple):
                pdbqt_str = writer_res[0]
                if len(writer_res) > 1 and not writer_res[1]:
                    err_msg = writer_res[2] if len(writer_res) > 2 else "Unknown error"
                    raise RuntimeError(f"Meeko setup failed: {err_msg}")
            else:
                pdbqt_str = str(writer_res)

            if not pdbqt_str or not pdbqt_str.strip():
                raise RuntimeError("Meeko generated empty PDBQT output")

            out_path.write_text(pdbqt_str, encoding="utf-8")
            _assert_generated_pdbqt(out_path)
            logger.info(f"Prepared ligand PDBQT via Meeko: {out_path}")
            result = calculate_molecule_descriptors(out_path)
            result["metal_diagnostics"] = _metal_diagnostics(out_path)
            try:
                from validators import inspect_pdbqt_charges
                result["charge_diagnostics"] = inspect_pdbqt_charges(out_path)
            except Exception as charge_err:
                result["charge_diagnostics"] = {"status": "UNAVAILABLE", "error": str(charge_err)}
            result["preparation_provenance"] = {
                "backend": "Meeko",
                "input": str(in_path),
                "generate_3d": generate_3d,
                "hydrogens_added": True,
                "reference_coordinates_preserved": not generate_3d,
            }
            return result

    except Exception as meeko_err:
        logger.warning(f"Meeko preparation notice ({meeko_err}), using OpenBabel...")

    # 2. OpenBabel fallback
    try:
        from executables import configure_openbabel_env
        configure_openbabel_env()
        from openbabel import pybel
        ext = in_path.suffix.lstrip(".").lower()
        ob_mol = next(pybel.readfile(ext, str(in_path)))
        ob_mol.addh()
        if generate_3d:
            try:
                if len(ob_mol.atoms) > 0 and ob_mol.atoms[0].coords == (0.0, 0.0, 0.0):
                    ob_mol.make3D()
            except Exception:
                pass
        pdbqt_content = ob_mol.write("pdbqt")
        if not pdbqt_content or not pdbqt_content.strip():
            raise RuntimeError("OpenBabel produced empty PDBQT output")
        out_path.write_text(pdbqt_content, encoding="utf-8")
        _assert_generated_pdbqt(out_path)
        logger.info(f"Prepared ligand PDBQT via OpenBabel: {out_path}")
        result = calculate_molecule_descriptors(out_path)
        result["metal_diagnostics"] = _metal_diagnostics(out_path)
        try:
            from validators import inspect_pdbqt_charges
            result["charge_diagnostics"] = inspect_pdbqt_charges(out_path)
        except Exception as charge_err:
            result["charge_diagnostics"] = {"status": "UNAVAILABLE", "error": str(charge_err)}
        result["preparation_provenance"] = {
            "backend": "OpenBabel",
            "input": str(in_path),
            "generate_3d": generate_3d,
            "hydrogens_added": True,
            "reference_coordinates_preserved": not generate_3d,
        }
        return result
    except Exception as ob_err:
        raise RuntimeError(f"Could not prepare ligand {input_file}: {ob_err}")


def split_flexible_receptor(
    receptor_pdbqt: Path | str,
    flex_residue_names: List[str],
    output_rigid_pdbqt: Path | str,
    output_flex_pdbqt: Path | str,
) -> Tuple[Path, Path]:
    """Splits a rigid receptor PDBQT into a rigid backbone and flexible sidechains pair.

    In AutoDock flexible receptor docking:
      - output_rigid_pdbqt retains non-flexible residues plus N, CA, C, O backbone of target residues.
      - output_flex_pdbqt contains sidechains wrapped in BEGIN_RES / ROOT / BRANCH / END_RES.

    Args:
        receptor_pdbqt: Path to existing receptor PDBQT.
        flex_residue_names: List of target residues (e.g. ['ILE:199', 'TYR:326'] or ['GLN 206']).
        output_rigid_pdbqt: Output path for rigid part.
        output_flex_pdbqt: Output path for flexible part.

    Returns:
        Tuple of (rigid_path, flex_path).
    """
    rec_path = Path(receptor_pdbqt)
    out_rigid = Path(output_rigid_pdbqt)
    out_flex = Path(output_flex_pdbqt)
    out_rigid.parent.mkdir(parents=True, exist_ok=True)
    out_flex.parent.mkdir(parents=True, exist_ok=True)

    # Normalize flex identifiers: extract sequence numbers and names
    flex_targets = set()
    for fr in flex_residue_names:
        clean = fr.replace(":", " ").strip()
        parts = clean.split()
        for p in parts:
            if p.isdigit():
                flex_targets.add(int(p))
            else:
                flex_targets.add(p.upper())

    rigid_lines = []
    flex_blocks: Dict[str, List[str]] = {}

    lines = rec_path.read_text(encoding="utf-8", errors="replace").splitlines()
    for line in lines:
        if line.startswith(("ATOM", "HETATM")):
            res_name = line[17:20].strip().upper()
            chain = line[21:22].strip() or "A"
            res_seq_str = line[22:26].strip()
            res_seq = int(res_seq_str) if res_seq_str.isdigit() else 0
            atom_name = line[12:16].strip().upper()

            is_flex = (res_seq in flex_targets) or (res_name in flex_targets)
            if is_flex:
                res_key = f"{res_name} {chain} {res_seq}"
                # Backbone atoms remain in rigid file
                if atom_name in ("N", "HN", "H", "C", "O"):
                    rigid_lines.append(line)
                else:
                    # CA and sidechain atoms go to flexible block
                    if res_key not in flex_blocks:
                        flex_blocks[res_key] = []
                    flex_blocks[res_key].append(line)
            else:
                rigid_lines.append(line)
        else:
            rigid_lines.append(line)

    # Write flexible PDBQT with valid AutoDock/Vina 1..N atom numbering per residue
    flex_lines = []
    for res_key, atom_lines in flex_blocks.items():
        flex_lines.append(f"BEGIN_RES {res_key}")
        flex_lines.append("ROOT")
        ca_line = None
        cb_line = None
        other_lines = []
        for l in atom_lines:
            if " CA " in l:
                ca_line = l
            elif " CB " in l:
                cb_line = l
            else:
                other_lines.append(l)

        # In AutoDock / Vina PDBQT flex residues, the ROOT contains CA (atom serial 1).
        # The BRANCH starts from atom 1 (CA) to atom 2 (CB).
        # All atoms in the flexible residue must have consecutive serial numbers 1, 2, 3...
        # so that BRANCH 1 2 and any torsional records resolve correctly.
        atom_serial = 1
        if ca_line:
            renumbered_ca = ca_line[:6] + f"{atom_serial:5d}" + ca_line[11:]
            flex_lines.append(renumbered_ca)
        flex_lines.append("ENDROOT")

        branch_atoms = []
        if cb_line:
            atom_serial += 1
            branch_atoms.append(cb_line[:6] + f"{atom_serial:5d}" + cb_line[11:])
        for l in other_lines:
            atom_serial += 1
            branch_atoms.append(l[:6] + f"{atom_serial:5d}" + l[11:])

        if branch_atoms:
            flex_lines.append("BRANCH 1 2")
            flex_lines.extend(branch_atoms)
            flex_lines.append("ENDBRANCH 1 2")
        flex_lines.append(f"END_RES {res_key}")

    out_rigid.write_text("\n".join(rigid_lines) + "\n", encoding="utf-8")
    out_flex.write_text("\n".join(flex_lines) + "\n", encoding="utf-8")

    logger.info(f"Split flexible receptor: {out_rigid} and {out_flex}")
    return (out_rigid, out_flex)


def sanitize_flex_pdbqt(flex_path: Path | str) -> bool:
    """Ensure flexible sidechain PDBQT has continuous 1..N serial numbers per residue matching BRANCH records."""
    p = Path(flex_path)
    if not p.is_file():
        return False
    try:
        lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
        new_lines = []
        modified = False
        atom_idx = 0
        in_res = False

        for l in lines:
            if l.startswith("BEGIN_RES"):
                atom_idx = 0
                in_res = True
                new_lines.append(l)
            elif l.startswith("END_RES"):
                in_res = False
                new_lines.append(l)
            elif in_res and l.startswith(("ATOM", "HETATM")):
                atom_idx += 1
                cur_serial_str = l[6:11].strip()
                cur_serial = int(cur_serial_str) if cur_serial_str.isdigit() else 0
                if cur_serial != atom_idx:
                    modified = True
                    new_lines.append(l[:6] + f"{atom_idx:5d}" + l[11:])
                else:
                    new_lines.append(l)
            else:
                new_lines.append(l)

        if modified:
            p.write_text("\n".join(new_lines) + "\n", encoding="utf-8")
            logger.info(f"Sanitized flexible receptor PDBQT atom indices: {p}")
            return True
    except Exception as e:
        logger.warning(f"Could not sanitize flex PDBQT {p}: {e}")
    return False


def calculate_molecule_descriptors(
    file_path: Path | str,
    obabel_exe: Optional[Path | str] = None,
    **kwargs,
) -> Dict[str, Any]:
    """Calculates physicochemical descriptors for a ligand from PDBQT/SDF/MOL2.

    All descriptors are computed from the 2D molecular graph using RDKit
    (deterministic calculations, no ML models involved).

    Properties and their citation basis:
      mw         — Molecular Weight (standard)
      logp       — Crippen–Wildman LogP (Crippen & Wildman, J Med Chem 1999)
      psa        — Topological Polar Surface Area (Ertl et al., J Med Chem 2000)
      hbd        — H-Bond Donors (Lipinski et al., Adv Drug Deliv Rev 1997)
      hba        — H-Bond Acceptors (Lipinski et al., 1997)
      rot_bonds  — Rotatable Bonds (Veber et al., J Med Chem 2002)
      arom_rings — Aromatic Ring Count (standard RDKit)
      lipinski   — Lipinski Rule of 5 (Lipinski et al., 1997)
                   Criteria: MW≤500, LogP≤5, HBD≤5, HBA≤10
      veber_pass — Veber oral bioavailability rules (Veber et al., 2002)
                   Criteria: PSA≤140 Å², RotBonds≤10
    """
    p = Path(file_path)
    info: Dict[str, Any] = {
        "name": p.stem,
        "stem": p.stem,
        "file_name": p.name,
        "mw": 0.0,
        "logp": 0.0,
        "psa": 0.0,
        "hbd": 0,
        "hba": 0,
        "rot_bonds": 0,
        "arom_rings": 0,
        "aromatic_rings": 0,
        "formula": "",
        "lipinski": "Pass",
        "ro5_pass": True,
        "veber_pass": True,
    }

    if not p.is_file():
        return info

    try:
        from openbabel import pybel
        from rdkit import Chem
        from rdkit.Chem import Descriptors, Lipinski, rdMolDescriptors

        ext = p.suffix.lstrip(".").lower()
        if ext not in ("pdbqt", "sdf", "mol2", "pdb"):
            ext = "pdbqt"

        ob_mol = next(pybel.readfile(ext, str(p)), None)
        if ob_mol:
            info["formula"] = ob_mol.formula
            info["mw"] = round(ob_mol.exactmass, 2)
            try:
                rdmol = Chem.MolFromMolBlock(ob_mol.write("mol"))
                if rdmol:
                    info["mw"] = round(Descriptors.MolWt(rdmol), 2)
                    info["logp"] = round(Descriptors.MolLogP(rdmol), 2)
                    info["psa"] = round(Descriptors.TPSA(rdmol), 2)
                    info["hbd"] = Lipinski.NumHDonors(rdmol)
                    info["hba"] = Lipinski.NumHAcceptors(rdmol)
                    info["rot_bonds"] = Lipinski.NumRotatableBonds(rdmol)
                    n_arom = rdMolDescriptors.CalcNumAromaticRings(rdmol)
                    info["arom_rings"] = n_arom
                    info["aromatic_rings"] = n_arom
            except Exception:
                pass
    except Exception:
        pass

    # Quick PDBQT rotatable bonds fallback if 0
    if info["rot_bonds"] == 0 and p.suffix.lower() == ".pdbqt":
        try:
            with open(p, "r", encoding="utf-8", errors="replace") as f:
                for line in f:
                    if "active torsions" in line:
                        parts = line.strip().split()
                        if len(parts) >= 2 and parts[1].isdigit():
                            info["rot_bonds"] = int(parts[1])
        except Exception:
            pass

    # Lipinski Rule of 5 (≤1 violation permitted per original paper)
    violations = 0
    if info["mw"] > 500:  violations += 1
    if info["logp"] > 5.0: violations += 1
    if info["hbd"] > 5:   violations += 1
    if info["hba"] > 10:  violations += 1
    info["lipinski"] = "Pass" if violations <= 1 else f"Fail ({violations}v)"
    info["ro5_pass"] = (violations <= 1)

    # Veber oral bioavailability criteria (both must be met)
    info["veber_pass"] = (info["psa"] <= 140.0 and info["rot_bonds"] <= 10)
    info["aromatic_rings"] = info.get("arom_rings", 0)

    return info


def inspect_receptor_residues(receptor_path: Path | str) -> List[Dict[str, Any]]:
    """Returns a list of unique residues in a receptor for active-site targeting and flex selection."""
    p = Path(receptor_path)
    if not p.is_file():
        return []

    residues = []
    seen = set()
    with open(p, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith(("ATOM", "HETATM")):
                res_name = line[17:20].strip().upper()
                chain = line[21:22].strip() or "A"
                res_seq_str = line[22:26].strip()
                res_seq = int(res_seq_str) if res_seq_str.isdigit() else 0
                key = (res_name, chain, res_seq)
                if key not in seen:
                    seen.add(key)
                    residues.append({
                        "name": res_name,
                        "chain": chain,
                        "seq": res_seq,
                        "label": f"{res_name} {chain} {res_seq}",
                    })
    return residues

def parse_hetatm_records(pdb_path: Path | str) -> List[Dict[str, Any]]:
    """Parse all unique HETATM entries from a PDB/CIF file for the GUI checklist.

    Returns a list of dicts with keys:
        key      — tuple (resname, chain, resseq) — usable as remove_residue_keys entry
        resname  — e.g. 'SAG'
        chain    — e.g. 'D'
        resseq   — integer sequence number
        label    — human-readable string e.g. 'SAG  D  401'
        is_water — True if this is a water molecule
    """
    WATER_NAMES = {"HOH", "WAT", "H2O"}
    METAL_ELEMENTS = {"MG", "CA", "MN", "FE", "ZN", "CU", "CO", "NI", "HG", "MO"}
    METAL_NAMES = METAL_ELEMENTS | {"MG2", "CA2", "MN2", "FE2", "FE3", "ZN2"}
    COFACTOR_NAMES = {"HEM", "HEME", "NAD", "FAD", "FMN", "SAM", "PLP", "ATP"}
    p = Path(pdb_path)
    if not p.is_file():
        return []

    entries: List[Dict[str, Any]] = []
    seen: set = set()
    metal_elements_by_key: Dict[tuple, set] = {}
    with open(p, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            if not line.startswith("HETATM"):
                continue
            resname = line[17:20].strip().upper()
            element = (line[76:78].strip() if len(line) >= 78 else "").upper()
            chain = line[21:22].strip() or "A"
            res_seq_str = line[22:26].strip()
            resseq = int(res_seq_str) if res_seq_str.isdigit() else 0
            key = (resname, chain, resseq)
            if key in seen:
                if element in METAL_ELEMENTS:
                    metal_elements_by_key.setdefault(key, set()).add(element)
                continue
            seen.add(key)
            metal_elements_by_key[key] = {element} if element in METAL_ELEMENTS else set()
            if resname in WATER_NAMES:
                component_type = "WATER"
            elif element in METAL_ELEMENTS or resname in METAL_NAMES:
                component_type = "METAL"
            elif resname in COFACTOR_NAMES:
                component_type = "COFACTOR"
            else:
                component_type = "UNKNOWN_COMPONENT"
            entries.append({
                "key": key,
                "resname": resname,
                "chain": chain,
                "resseq": resseq,
                "label": f"{resname:<4s} {chain}  {resseq}",
                "is_water": resname in WATER_NAMES,
                "element": element,
                "component_type": component_type,
                "classification_status": "validated_name_or_element" if component_type != "UNKNOWN_COMPONENT" else "user_review_required",
                "metal_elements": sorted(metal_elements_by_key[key]),
            })

    # Sort: waters last, then alphabetical by resname
    entries.sort(key=lambda e: (not e["is_water"], e["resname"], e["resseq"]))
    for entry in entries:
        metals = sorted(metal_elements_by_key.get(entry["key"], set()))
        entry["metal_elements"] = metals
        if metals and entry["component_type"] == "COFACTOR":
            entry["classification_status"] = "cofactor_contains_metal"
    return entries


def parse_pdb_chains(pdb_path: Path | str) -> List[Dict[str, Any]]:
    """Parse all chains present in a PDB/CIF file.

    Returns a list of dicts:
        chain: chain identifier (e.g. 'A')
        atom_count: total ATOM + HETATM count
        residue_count: count of unique residues in this chain
        res_start: first residue sequence number
        res_end: last residue sequence number
        label: formatted summary string e.g. 'Chain A — 1,450 atoms (res 1–295)'
    """
    p = Path(pdb_path)
    if not p.is_file():
        return []

    chains_data: Dict[str, Dict[str, Any]] = {}
    with open(p, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith(("ATOM", "HETATM")):
                chain = (line[21:22].strip() or "A").upper()
                res_seq_str = line[22:26].strip()
                res_seq = int(res_seq_str) if res_seq_str.isdigit() else 0

                if chain not in chains_data:
                    chains_data[chain] = {
                        "chain": chain,
                        "atoms": 0,
                        "residues": set(),
                    }
                chains_data[chain]["atoms"] += 1
                if res_seq != 0:
                    chains_data[chain]["residues"].add(res_seq)

    result = []
    for chain in sorted(chains_data.keys()):
        d = chains_data[chain]
        res_list = sorted(d["residues"])
        res_start = res_list[0] if res_list else 1
        res_end = res_list[-1] if res_list else 1
        n_res = len(res_list)
        label = f"Chain {chain}  -  {d['atoms']:,} atoms ({n_res} residues: {res_start}-{res_end})"
        result.append({
            "chain": chain,
            "atom_count": d["atoms"],
            "residue_count": n_res,
            "res_start": res_start,
            "res_end": res_end,
            "label": label,
        })
    return result


def parse_pdb_residues(pdb_path: Path | str) -> List[Dict[str, Any]]:
    """Parse all amino acid residues from ATOM records in a PDB file for editing and mutation.

    Returns a list of dicts:
        chain: chain ID e.g. 'A'
        seq: sequence number integer e.g. 123
        name: 3-letter residue name e.g. 'ASP'
        atom_count: number of atoms in this residue
        key: tuple (chain, seq)
        label: e.g. 'Chain A : ASP 123 (8 atoms)'
    """
    p = Path(pdb_path)
    if not p.is_file():
        return []

    residues: Dict[Tuple[str, int], Dict[str, Any]] = {}
    with open(p, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("ATOM"):
                chain = (line[21:22].strip() or "A").upper()
                res_name = line[17:20].strip().upper()
                res_seq_str = line[22:26].strip()
                res_seq = int(res_seq_str) if res_seq_str.isdigit() else 0
                key = (chain, res_seq)
                if key not in residues:
                    residues[key] = {
                        "chain": chain,
                        "seq": res_seq,
                        "name": res_name,
                        "atoms": 0,
                        "key": key,
                    }
                residues[key]["atoms"] += 1

    result = []
    for key, d in sorted(residues.items(), key=lambda kv: (kv[0][0], kv[0][1])):
        d["atom_count"] = d["atoms"]
        d["label"] = f"Chain {d['chain']} : {d['name']:<4s} {d['seq']} ({d['atoms']} atoms)"
        result.append(d)
    return result


def get_coligand_bbox(
    ligand_path: Path | str,
    padding: float = 5.0,
) -> Optional[Dict[str, float]]:
    """Compute bounding-box center and padded size from a ligand SDF/MOL2/PDB.

    Returns a dict with keys: center_x, center_y, center_z, size_x, size_y, size_z
    or None if the file cannot be parsed.

    Args:
        ligand_path: Path to SDF, MOL2, or PDB file.
        padding: Extra Ångströms added on each side of the bounding box.
    """
    p = Path(ligand_path)
    if not p.is_file():
        return None

    coords: List[tuple] = []

    # Try RDKit first
    try:
        from rdkit import Chem
        ext = p.suffix.lower()
        mol = None
        if ext in (".sdf", ".mol"):
            suppl = Chem.SDMolSupplier(str(p), removeHs=True)
            mol = next(suppl, None)
        elif ext == ".mol2":
            mol = Chem.MolFromMol2File(str(p), removeHs=True)
        elif ext == ".pdb":
            mol = Chem.MolFromPDBFile(str(p), removeHs=True)
        if mol and mol.GetNumConformers() > 0:
            conf = mol.GetConformer(0)
            for i in range(mol.GetNumAtoms()):
                pos = conf.GetAtomPosition(i)
                coords.append((pos.x, pos.y, pos.z))
    except Exception:
        pass

    # Fallback: OpenBabel
    if not coords:
        try:
            from openbabel import pybel
            ext = p.suffix.lstrip(".").lower()
            ob_mol = next(pybel.readfile(ext, str(p)), None)
            if ob_mol:
                for atom in ob_mol.atoms:
                    coords.append(atom.coords)
        except Exception:
            pass

    if not coords:
        return None

    xs = [c[0] for c in coords]
    ys = [c[1] for c in coords]
    zs = [c[2] for c in coords]

    cx = (min(xs) + max(xs)) / 2.0
    cy = (min(ys) + max(ys)) / 2.0
    cz = (min(zs) + max(zs)) / 2.0
    sx = (max(xs) - min(xs)) + 2 * padding
    sy = (max(ys) - min(ys)) + 2 * padding
    sz = (max(zs) - min(zs)) + 2 * padding

    return {
        "center_x": round(cx, 3),
        "center_y": round(cy, 3),
        "center_z": round(cz, 3),
        "size_x": round(sx, 3),
        "size_y": round(sy, 3),
        "size_z": round(sz, 3),
    }


