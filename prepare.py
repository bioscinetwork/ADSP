def _restore_cif_identity_columns(pdbqt_path: Path, cif_path: Path) -> None:
    """Restore chain/residue/component columns lost by some CIF writers."""
    try:
        import tempfile
        import gemmi
        metadata_path = Path(tempfile.NamedTemporaryFile(suffix=".pdb", delete=False).name)
        try:
            gemmi.read_structure(str(cif_path)).write_pdb(str(metadata_path))
            source = [line for line in metadata_path.read_text(encoding="utf-8", errors="replace").splitlines()
                      if line.startswith(("ATOM", "HETATM"))]
        finally:
            metadata_path.unlink(missing_ok=True)
        records = []
        for line in source:
            try:
                records.append((line, float(line[30:38]), float(line[38:46]), float(line[46:54])))
            except (ValueError, IndexError):
                pass
        if not records:
            return
        rewritten = []
        for line in pdbqt_path.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith(("ATOM", "HETATM")) and len(line) >= 54:
                try:
                    x, y, z = float(line[30:38]), float(line[38:46]), float(line[46:54])
                    source_line = min(records, key=lambda item: (item[1]-x)**2 + (item[2]-y)**2 + (item[3]-z)**2)[0]
                    line = line[:16] + source_line[16:27] + line[27:]
                except (ValueError, IndexError):
                    pass
            rewritten.append(line)
        pdbqt_path.write_text("\n".join(rewritten) + "\n", encoding="utf-8")
    except Exception as exc:
        logger.debug(f"CIF identity restoration unavailable: {exc}")


def prepare_receptor_pdbqt(
    input_file: Path | str,
    output_pdbqt: Path | str,
    cleanup_water: bool = True,
    add_hydrogens: bool = True,
    remove_residue_keys: Optional[set] = None,
    remove_chains: Optional[set] = None,
    mutations: Optional[dict] = None,
    deleted_residues: Optional[set] = None,
    charge_model: str = "kollman",
) -> Path:
    """Prepares a raw macromolecule PDB/CIF file into an AutoDock-ready PDBQT.

    1. Removes whole chains selected in *remove_chains* (e.g. stripping redundant monomer chain).
    2. Removes deleted residues in *deleted_residues* and HETATM records in *remove_residue_keys*.
    3. Applies point mutations / renaming in *mutations* (truncating ALA/GLY sidechains, updating resnames).
    4. Removes water (HOH, WAT) if cleanup_water is True.
    5. Adds polar hydrogens (at physiological pH).
    6. Computes partial charges (ADSP Kollman-style fallback or Gasteiger) and assigns AutoDock 4 atom types.
    7. Saves intermediate edited PDB alongside PDBQT for full inspection.

    Args:
        input_file: Source PDB or CIF file.
        output_pdbqt: Destination PDBQT path.
        cleanup_water: Strip waters and crystallographic salts.
        add_hydrogens: Add necessary hydrogens.
        remove_residue_keys: Set of (resname, chain, resseq) tuples to strip.
        remove_chains: Set of chain IDs (e.g. {'B'}) to completely remove.
        mutations: Dict mapping (chain, resseq) -> target_resname (e.g. {('A', 123): 'ALA'}).
        deleted_residues: Set of (chain, resseq) tuples to remove entirely.
        charge_model: 'kollman' (ADSP Kollman-style fallback; not canonical ADT/MGLTools) or 'gasteiger'.

    Returns:
        Resolved Path to output PDBQT.
    """
    in_path = Path(input_file).resolve()
    out_path = Path(output_pdbqt).resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    _remove_keys: set = remove_residue_keys or set()
    _remove_chains: set = {str(c).strip().upper() for c in (remove_chains or set())}
    _deleted_residues: set = {(str(c).strip().upper(), int(s)) for (c, s) in (deleted_residues or set())}
    _mutations: dict = {(str(c).strip().upper(), int(s)): str(m).strip().upper() for (c, s), m in (mutations or {}).items()}

    # Backbone atoms preserved when mutating to ALA or GLY
    ALA_BACKBONE_ATOMS = {"N", "CA", "C", "O", "CB", "H", "HN", "HA", "OXT"}
    GLY_BACKBONE_ATOMS = {"N", "CA", "C", "O", "H", "HN", "HA", "HA1", "HA2", "OXT"}

    WATER_NAMES = DEFAULT_CLEANUP_COMPONENTS

    if not in_path.is_file():
        raise FileNotFoundError(f"Receptor file not found: {in_path}")

    # Step 1: Cleanly filter PDB lines (remove chains, deleted residues, waters, HETATMs, apply mutations)
    raw_lines = in_path.read_text(encoding="utf-8", errors="replace").splitlines()
    clean_lines = []
    for line in raw_lines:
        if line.startswith(("ATOM", "HETATM")):
            atom_name = line[12:16].strip()
            res_name = line[17:20].strip().upper()
            chain = (line[21:22].strip() or "A").upper()
            res_seq_str = line[22:26].strip()
            res_seq = int(res_seq_str) if res_seq_str.isdigit() else 0

            # 1. Filter out whole removed chains
            if chain in _remove_chains:
                continue

            # 2. Filter out deleted residues
            if (chain, res_seq) in _deleted_residues:
                continue

            # 3. Filter out water if requested
            if cleanup_water and res_name in WATER_NAMES:
                continue

            # 4. Filter out specific HETATM entries
            het_key = (res_name, chain, res_seq)
            if het_key in _remove_keys:
                continue

            # 5. Apply point mutations / renaming
            res_key = (chain, res_seq)
            if res_key in _mutations:
                target_res = _mutations[res_key]
                if target_res == "ALA":
                    if atom_name not in ALA_BACKBONE_ATOMS:
                        continue  # Truncate sidechain beyond CB
                    line = line[:17] + f"{target_res:>3s}" + line[20:]
                elif target_res == "GLY":
                    if atom_name not in GLY_BACKBONE_ATOMS:
                        continue  # Truncate sidechain beyond CA
                    line = line[:17] + f"{target_res:>3s}" + line[20:]
                else:
                    line = line[:17] + f"{target_res:>3s}" + line[20:]

            clean_lines.append(line)
        elif line.startswith("TER"):
            ter_chain = (line[21:22].strip() or "").upper()
            if ter_chain and ter_chain in _remove_chains:
                continue
            clean_lines.append(line)
        elif line.startswith(("END", "CONECT")):
            clean_lines.append(line)

    clean_pdb_str = "\n".join(clean_lines) + "\n"

    # Save intermediate cleaned & edited PDB file
    edited_pdb = out_path.parent / f"{out_path.stem}_edited.pdb"
    if out_path.parent.name == "rigid":
        edited_pdb = out_path.parent.parent / f"{out_path.stem}_edited.pdb"
    try:
        edited_pdb.write_text(clean_pdb_str, encoding="utf-8")
        logger.info(f"Saved intermediate edited PDB: {edited_pdb}")
    except Exception:
        pass

    # Step 2: Try OpenBabel CLI
    converted = False
    try:
        from executables import resolve_executable
        ob_exe = resolve_executable(None, "obabel.exe")
        if ob_exe and ob_exe.is_file():
            import tempfile, subprocess
            with tempfile.NamedTemporaryFile(suffix=".pdb", mode="w", encoding="utf-8", delete=False) as tf:
                tf.write(clean_pdb_str)
                tmp_pdb = Path(tf.name)
            try:
                # CIF/mmCIF must be passed to OpenBabel as CIF. Treating CIF
                # text as PDB silently corrupts columns and coordinates.
                input_format = "cif" if in_path.suffix.lower() in (".cif", ".mmcif") else "pdb"
                source_path = in_path if input_format == "cif" else tmp_pdb
                if input_format == "cif":
                    # Prefer gemmi for mmCIF -> PDB normalization.  It
                    # preserves author chain/residue identifiers that can be
                    # lost by direct OpenBabel conversion.  OpenBabel remains
                    # the PDBQT writer and is retained as the fallback when
                    # gemmi is unavailable or cannot read the input.
                    normalized_pdb = Path(tempfile.NamedTemporaryFile(suffix=".pdb", delete=False).name)
                    normalize = None
                    try:
                        import gemmi
                        structure = gemmi.read_structure(str(source_path))
                        structure.write_pdb(str(normalized_pdb))
                        normalize_ok = normalized_pdb.is_file() and normalized_pdb.stat().st_size > 100
                    except Exception as gemmi_err:
                        logger.debug(f"gemmi CIF normalization failed ({gemmi_err}); trying OpenBabel")
                        normalize = subprocess.run(
                            [str(ob_exe), "-icif", str(source_path), "-opdb", "-O", str(normalized_pdb)],
                            capture_output=True, text=True, timeout=30,
                        )
                        normalize_ok = normalize.returncode == 0 and normalized_pdb.is_file()
                    if normalize_ok:
                        # OpenBabel may emit ``*`` for the element column on
                        # CIF records. Recover unambiguous elemental symbols
                        # from atom/residue names before PDBQT typing.
                        normalized_lines = []
                        for normalized_line in normalized_pdb.read_text(encoding="utf-8", errors="replace").splitlines():
                            if normalized_line.startswith(("ATOM", "HETATM")):
                                residue_name = normalized_line[17:20].strip().upper()
                                if cleanup_water and residue_name in WATER_NAMES:
                                    continue
                            if normalized_line.startswith(("ATOM", "HETATM")):
                                atom_name = normalized_line[12:16].strip().upper()
                                residue_name = normalized_line[17:20].strip().upper()
                                inferred = ""
                                for candidate in (atom_name, residue_name):
                                    if candidate in {"ZN", "FE", "MG", "MN", "CA", "CU", "CO", "NI", "HG", "MO"}:
                                        inferred = candidate.title()
                                        break
                                if inferred:
                                    normalized_line = normalized_line[:76] + f"{inferred:>2s}" + normalized_line[78:]
                            normalized_lines.append(normalized_line)
                        normalized_pdb.write_text("\n".join(normalized_lines) + "\n", encoding="utf-8")
                        source_path = normalized_pdb
                        input_format = "pdb"
                cmd = [str(ob_exe), f"-i{input_format}", str(source_path), "-opdbqt", "-O", str(out_path), "--partialcharge", "gasteiger", "-xr"]
                res = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
                if out_path.is_file() and out_path.stat().st_size > 100:
                    # Preserve explicit metal atom types when OpenBabel leaves
                    # the PDBQT AutoDock type column blank for CIF-derived
                    # records.
                    typed_lines = []
                    source_atom_lines = []
                    if in_path.suffix.lower() in (".cif", ".mmcif"):
                        try:
                            import gemmi
                            metadata_pdb = Path(tempfile.NamedTemporaryFile(suffix=".pdb", delete=False).name)
                            gemmi.read_structure(str(in_path)).write_pdb(str(metadata_pdb))
                            source_atom_lines = [
                                line for line in metadata_pdb.read_text(encoding="utf-8", errors="replace").splitlines()
                                if line.startswith(("ATOM", "HETATM"))
                            ]
                        except Exception:
                            source_atom_lines = []
                        finally:
                            try:
                                metadata_pdb.unlink(missing_ok=True)
                            except Exception:
                                pass
                    if not source_atom_lines and input_format == "pdb" and 'normalized_pdb' in locals() and normalized_pdb.is_file():
                        source_atom_lines = [
                            line for line in normalized_pdb.read_text(encoding="utf-8", errors="replace").splitlines()
                            if line.startswith(("ATOM", "HETATM"))
                        ]
                    source_records = []
                    for source_line in source_atom_lines:
                        try:
                            source_records.append((
                                source_line,
                                source_line[12:16].strip().upper(),
                                float(source_line[30:38]), float(source_line[38:46]), float(source_line[46:54]),
                            ))
                        except (ValueError, IndexError):
                            continue
                    # Metadata transfer is intentionally best-effort; the
                    # source records are only used to restore identity fields.
                    for output_line in out_path.read_text(encoding="utf-8", errors="replace").splitlines():
                        if output_line.startswith(("ATOM", "HETATM")) and len(output_line) >= 79:
                            # OpenBabel can rewrite all CIF-derived records as
                            # chain B/residue 0.  Transfer only the structural
                            # identity columns from the metadata-preserving
                            # normalized PDB; coordinates, charges, and AD4
                            # typing remain those generated by OpenBabel.
                            source_line = None
                            try:
                                ox, oy, oz = float(output_line[30:38]), float(output_line[38:46]), float(output_line[46:54])
                                oname = output_line[12:16].strip().upper()
                                candidates = [r for r in source_records if r[1] == oname] or source_records
                                if candidates:
                                    source_line = min(candidates, key=lambda r: (r[2]-ox)**2 + (r[3]-oy)**2 + (r[4]-oz)**2)[0]
                            except (ValueError, IndexError):
                                pass
                            if source_line is not None:
                                if len(source_line) >= 27:
                                    output_line = (
                                        output_line[:16] + source_line[16:27] + output_line[27:]
                                    )
                            atom_name = output_line[12:16].strip().upper()
                            residue_name = output_line[17:20].strip().upper()
                            inferred_type = next((candidate.title() for candidate in (atom_name, residue_name)
                                                  if candidate in {"ZN", "FE", "MG", "MN", "CA", "CU", "CO", "NI", "HG", "MO"}), None)
                            if inferred_type:
                                output_line = output_line[:77] + f"{inferred_type:>2s}" + output_line[79:]
                        typed_lines.append(output_line)
                    out_path.write_text("\n".join(typed_lines) + "\n", encoding="utf-8")
                    if in_path.suffix.lower() in (".cif", ".mmcif"):
                        _restore_cif_identity_columns(out_path, in_path)
                    converted = True
                if 'normalized_pdb' in locals():
                    normalized_pdb.unlink(missing_ok=True)
            finally:
                try:
                    tmp_pdb.unlink(missing_ok=True)
                except Exception:
                    pass
    except Exception as ob_cmd_err:
        logger.debug(f"obabel CLI conversion failed ({ob_cmd_err}), trying pybel...")

    # Step 3: Try OpenBabel pybel on clean PDB text if CLI failed
    if not converted:
        try:
            from openbabel import pybel
            input_format = "cif" if in_path.suffix.lower() in (".cif", ".mmcif") else "pdb"
            mol = pybel.readstring(input_format, in_path.read_text(encoding="utf-8", errors="replace") if input_format == "cif" else clean_pdb_str)
            if add_hydrogens:
                try:
                    mol.addh()
                except Exception:
                    pass
            pdbqt_content = mol.write("pdbqt", opt={"r": None})
            if pdbqt_content and len(pdbqt_content.strip()) > 50:
                out_path.write_text(pdbqt_content, encoding="utf-8")
                converted = True
        except Exception as ob_err:
            logger.debug(f"OpenBabel readstring failed ({ob_err}), using pure Python fallback...")

    # Step 4: Pure Python PDB to PDBQT cleaner fallback
    if not converted:
        out_lines = []
        for line in clean_lines:
            if line.startswith(("ATOM", "HETATM")):
                atom_name = line[12:16].strip()
                element = line[76:78].strip() if len(line) >= 78 else atom_name[0]
                ad_type = element.upper()
                if ad_type in ("C", "A", "N", "NA", "OA", "SA", "HD", "CL", "BR", "F", "I", "P"):
                    pass
                elif element == "O":
                    ad_type = "OA"
                elif element == "N":
                    ad_type = "NA" if "A" in atom_name else "N"
                elif element == "H":
                    ad_type = "HD" if atom_name.startswith(("HN", "HE", "HH", "HD")) else "H"
                pdbqt_line = f"{line[:54]:<54}  1.00 20.00    +0.000 {ad_type:<2s}"
                out_lines.append(pdbqt_line)
            elif line.startswith(("TER", "END")):
                out_lines.append(line)
        out_path.write_text("\n".join(out_lines) + "\n", encoding="utf-8")

    # Step 5: Charge Assignment (ADSP Kollman-style fallback vs Gasteiger)
    if charge_model.lower().startswith("kollman"):
        assign_kollman_charges(out_path)
    else:
        ensure_receptor_has_charges(out_path)

    # Final guard for CIF-derived metal records: charge rewriting can inherit
    # a blank element/type column from OpenBabel, so restore unambiguous AD4
    # metal types from atom and residue names.
    if in_path.suffix.lower() in (".cif", ".mmcif") and out_path.is_file():
        fixed = []
        metal_names = {"ZN", "FE", "MG", "MN", "CA", "CU", "CO", "NI", "HG", "MO"}
        for line in out_path.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith(("ATOM", "HETATM")):
                atom_name = line[12:16].strip().upper()
                residue_name = line[17:20].strip().upper()
                if cleanup_water and residue_name in WATER_NAMES:
                    continue
                metal = next((candidate.title() for candidate in (atom_name, residue_name) if candidate in metal_names), None)
                if metal and len(line) >= 77:
                    line = line[:77] + f"{metal:>2s}" + line[79:]
            fixed.append(line)
        out_path.write_text("\n".join(fixed) + "\n", encoding="utf-8")
        _restore_cif_identity_columns(out_path, in_path)

    _assert_generated_pdbqt(out_path)
    charge_label = "ADSP Kollman-style fallback" if charge_model.lower().startswith("kollman") else "OpenBabel Gasteiger"
    logger.info(f"Prepared receptor PDBQT via {charge_label}: {out_path}")
    return out_path


