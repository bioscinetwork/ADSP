def _prompt_float(prompt: str, default: float) -> float:
    """Prompt for a float value with a default."""
    try:
        raw = input(f"  {prompt} [{default}]: ").strip()
        return float(raw) if raw else default
    except (ValueError, EOFError):
        return default


def prepare_vina_configs(
    config,  # ProjectConfig
    batch_center: Optional[Tuple[float, float, float]] = None,
    batch_size: Optional[Tuple[float, float, float]] = None,
) -> List[Path]:
    """Auto-generate missing config.txt files for all receptors.

    For each receptor without a config.txt:
        - If auto_generate_config is True AND batch_center/size are set in
          project_config.toml, generate silently.
        - Otherwise, interactively prompt the user for center/size values.

    Returns:
        List of config.txt paths that were created.
    """
    from job_manager import discover_receptors, find_receptor_config

    receptors = discover_receptors(config)
    created: List[Path] = []

    print()
    print("=" * 60)
    print("  AUTODOCK SUITE PRO — PREPARE: VINA CONFIG FILES")
    print("=" * 60)

    for rec_name, rec_dir, mode in receptors:
        existing_config = find_receptor_config(rec_dir, rec_name)
        if existing_config and existing_config.exists():
            print(f"  [SKIP] {rec_name}: config.txt already exists ({existing_config.name})")
            continue

        print(f"\n  [MISSING] {rec_name}: no config.txt found.")

        # Try batch values from config
        if batch_center and batch_size:
            cx, cy, cz = batch_center
            sx, sy, sz = batch_size
            print(f"    Using batch values: center=({cx}, {cy}, {cz}), size=({sx}, {sy}, {sz})")
        else:
            print(f"    Enter grid box parameters for '{rec_name}':")
            print(f"    (Tip: open the receptor in PyMOL or UCSF Chimera to find center)")
            cx = _prompt_float("center_x", 0.0)
            cy = _prompt_float("center_y", 0.0)
            cz = _prompt_float("center_z", 0.0)
            sx = _prompt_float("size_x (Angstroms)", 25.0)
            sy = _prompt_float("size_y (Angstroms)", 25.0)
            sz = _prompt_float("size_z (Angstroms)", 25.0)

        config_path = rec_dir / "config.txt"
        write_vina_config(
            config_path,
            center_x=cx, center_y=cy, center_z=cz,
            size_x=sx, size_y=sy, size_z=sz,
            exhaustiveness=config.exhaustiveness,
            num_modes=config.num_modes,
            energy_range=config.energy_range,
        )
        created.append(config_path)
        print(f"    [OK] Written: {config_path}")

    print()
    print(f"  Done. {len(created)} config.txt file(s) created.")
    print("=" * 60)
    return created


