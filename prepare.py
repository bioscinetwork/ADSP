def _assert_generated_pdbqt(path: Path) -> None:
    """Reject malformed newly generated PDBQT before exposing it downstream."""
    from validators import validate_pdbqt
    valid, errors = validate_pdbqt(path)
    if not valid:
        raise RuntimeError(
            f"Generated PDBQT failed fixed-column validation: {path}: "
            + "; ".join(errors[:4])
        )

DEFAULT_CLEANUP_COMPONENTS = frozenset({"HOH", "WAT", "H2O", "EDO", "GOL", "SO4", "PO4", "DMS"})


def cleanup_provenance(source_path: Path | str, *, cleanup_water: bool = True,
                       removed_keys: Optional[set[tuple[str, str, int]]] = None) -> dict:
    """Return explicit component retention/removal decisions for a preparation."""
    records = parse_hetatm_records(source_path)
    removed_keys = removed_keys or set()
    retained, removed = [], []
    for record in records:
        key = record["key"]
        if key in removed_keys:
            reason = "user_selected_removal"
            removed.append({**record, "decision": "removed", "reason": reason})
        elif cleanup_water and record["resname"] in DEFAULT_CLEANUP_COMPONENTS:
            reason = "default_cleanup_rule"
            removed.append({**record, "decision": "removed", "reason": reason})
        else:
            reason = "retained_by_default"
            retained.append({**record, "decision": "retained", "reason": reason})
    return {
        "source": str(Path(source_path)),
        "cleanup_water": cleanup_water,
        "default_cleanup_components": sorted(DEFAULT_CLEANUP_COMPONENTS),
        "input_components": records,
        "retained_components": retained,
        "removed_components": removed,
        "cleanup_rules": {
            "water_and_crystallographic_components": sorted(DEFAULT_CLEANUP_COMPONENTS),
        },
        "user_overrides": sorted([
            {"resname": k[0], "chain": k[1], "residue_seq": k[2]}
            for k in removed_keys
        ], key=lambda x: (x["resname"], x["chain"], x["residue_seq"])),
        "warnings": [],
        "scientific_component_relevance_established": False,
    }

